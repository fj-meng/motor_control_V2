/*
 * 机致电机控制模块
 *
 * 使用「速度力矩控制 + 增量位置模式」，控制帧全部是标准帧：
 *   上电或 motormod2init 时切模式并把目标速度和限流写进去，但**不启动**，
 *   电机保持静止。真正让它转需要显式调用 Motor_StartSpeed()。
 *
 * 为什么用增量位置模式而不是单圈绝对位置模式：
 *   单圈模式的位置量程只有 ±360°，连续同向旋转会顶在 0xFFFF 不再更新
 *   （2026-10-23 实测），拿不到连续角度。增量模式位置是 32 位、
 *   20bit 分辨率、最大 ±2048 圈，应答从 6 字节变 8 字节。
 *
 * 协议依据：手册 7.4（标准帧）、7.6（增量模式）、7.8.1（连续旋转实例）。
 *
 * 用扩展帧的只有两条：切增量模式（全 0）和自动上传开关（00 05 01）。
 */

#ifndef MOTOR_DRIVER_H
#define MOTOR_DRIVER_H

#include "xil_types.h"

/*
 * 上电自动初始化开关：
 *   1 = main() 里调用 Motor_InitSpeedMode()，只建模式不启动；
 *   0 = 不碰电机，只跑 CAN 接收。
 */
#define MOTOR_AUTO_INIT         1

/*
 * 是否用「自动上传」而不是「定时器轮询」来拿数据。
 *
 *   0 = 定时器中断轮询（**默认，推荐**）：每 1ms 由私有定时器中断发一条
 *       速度指令，电机回一条应答。间隔由硬件保证，不受 SD 落盘和串口
 *       打印影响。
 *   1 = 打开电机的自动上传（00 05 01），被动收 1kHz 数据流。
 *       实测这条路径在这台电机上不稳定：跑几秒就断、REC 打满、电机静默。
 *
 * 上位机（厂家工具）从来不用自动上传，一直是「发一条收一条」。
 */
#define MOTOR_AUTO_UPLOAD_ON_INIT   0

/*
 * 周期轮询间隔（微秒）。
 * 手册规定最小通讯间隔 500us（2kHz），这里取 1ms 留一倍余量。
 */
#define MOTOR_POLL_PERIOD_US    1000U

/*
 * 轮询每拍在速度指令之外，额外发哪一条特殊帧。
 *
 *   0 = 只发速度指令（**默认**）
 *       电机按设定速度稳定运行。实测它不回应答（速度没变化 = 状态没变化
 *       = 不回），poll 正常但 rx=0。
 *   1 = 先发 FF...FD（停止）再发速度指令
 *       **电机不转**：FD 每 1ms 停一次，普通指令恢复不了使能。
 *   2 = 先发速度指令再发 FF...FC（启动）
 *       能逼出应答（实测收到 4257 帧），但有两个副作用：
 *       ① **电机跑到满速 58.6 rad/s（560 RPM）**，不是设定值
 *          —— FC 每拍重新启动把速度设定覆盖掉了，很危险；
 *       ② 约 2 秒后应答断流（≈2128 拍，接近 2048，像电机发送队列积压）。
 *   3 = 速度码微抖动：相邻两拍分别用 N 和 N+1
 *       ±1 码 = 0.27 RPM，转速上完全看不出来，但每拍都是「新的设定」，
 *       用来验证「电机只在状态变化时回应答」这个假设。
 *       不会停机、不会满速，是最安全的试探方式。
 *
 * 运行时用串口命令 `motorpoll 0|1|2|3` 切换，不用重新烧录。
 */
#define MOTOR_POLL_TAIL_DEFAULT 0

/*
 * 目标转速和限流。motormod2init 用的就是这两个值。
 *
 * 换算（手册 7.4.2，全部按 12 位码，零点 0x800）：
 *   50 RPM -> 50*2π/60 = 5.236 rad/s
 *           -> (5.236/58.639)*2048 + 2048 = 2230 = 0x8B6
 *   0.5 A  -> (0.5/32)*2048 + 2048 = 2080 = 0x820
 *
 * 对应的普通指令帧：80 00 8B 60 00 00 08 20
 *   位置=0x8000(0度)  速度=0x8B6  Kp=0  Kd=0  力矩=0x820
 */
#define MOTOR_TARGET_SPEED_RPM  50.0f  /* 目标转速，单位 RPM */
#define MOTOR_TARGET_CURRENT_A  0.5f   /* 运行最大电流，单位 A */

/*
 * 初始化时是否把当前位置设为零点（发 FF FF FF FF FF FF FF FE）。
 *
 *   1 = 每次 motormod2init 都把当前位置清成 0，位置从 0 开始累加
 *   0 = 保留电机原来的零点，位置从当前值开始累加
 *
 * 手册说机械零位掉电不保存，所以这个操作只在本次上电内有效。
 * 如果电机做过机械对零，不想被覆盖，把它改成 0。
 */
#define MOTOR_ZERO_ON_INIT      1

/*
 * 切到「速度力矩 + 增量位置」模式，写入目标速度和限流，但不启动。
 *
 * 顺序：停止(FF...FD) → 切回单圈(02 00) → 切速度力矩(FF...FA) →
 *       切增量位置模式(扩展帧全 0) → [清零(FF...FE)] → 普通指令(速度+限流)
 *
 * **为什么第一步要切回单圈**：电机不会因为 ARM 重烧程序而复位，它保留着
 * 上一次留下的模式。如果上次停在增量模式，再发一次「切增量」会让电机彻底
 * 静默（CAN 照样 ACK 但固件不再应答），只有给电机断电才恢复。
 * 所以每次初始化都先拉回上电默认状态，不依赖之前是什么模式。
 *
 * **为什么用增量模式**：单圈绝对位置模式的位置量程只有 ±360°，连续同向
 * 旋转会顶在 0xFFFF 不动，拿不到连续角度。增量模式位置是 32 位、
 * 20bit 分辨率、最大 ±2048 圈，应答从 6 字节变 8 字节。
 *
 * 该模式**掉电不保持**，电机每次上电都要重新切一次。
 *
 * 返回 XST_SUCCESS 只表示帧都已成功发出，不代表电机一定接受了。
 */
int Motor_InitSpeedMode(float speed_rpm, float current_a);

/*
 * 参数是否已经写入过电机（即 Motor_InitSpeedMode 是否成功）。
 *
 * 上电后电机状态未定义，没跑过初始化就直接启动，电机可能按未知的
 * 速度/电流跑起来。串口 motoron 命令靠这个标志挡住误操作。
 */
int Motor_IsReady(void);

/*
 * 启动电机（FF FF FF FF FF FF FF FC）。
 * 会先把速度和限流重写一遍再启动，避免电机中途掉电后参数丢失。
 */
int Motor_StartSpeed(void);

/* 停止电机（FF FF FF FF FF FF FF FD），无输出力，处于自由状态。 */
int Motor_StopSpeed(void);

/* 改目标速度，只重写参数帧，不动启动/停止状态。 */
int Motor_SetSpeedRpm(float speed_rpm);

/*
 * 周期轮询（私有定时器中断驱动）。
 *
 * 启动后每 MOTOR_POLL_PERIOD_US 由定时器中断发一条速度指令，电机回一条
 * 应答。间隔由硬件保证，主循环再怎么忙（SD 落盘、串口打印）都不影响。
 *
 * 由 Motor_StartSpeed() 自动启动、Motor_StopSpeed() 自动停止，
 * 一般不需要手动调用。
 */
int Motor_StartPolling(void);
void Motor_StopPolling(void);
int Motor_IsPolling(void);

/* 轮询统计：实际发出的速度指令拍数、因 TX FIFO 满而跳过的拍数。 */
u32 Motor_GetPollTicks(void);
u32 Motor_GetPollMiss(void);

/* 轮询尾帧（FD 或 FC）的发送统计，模式 0 时恒为 0。 */
u32 Motor_GetPollTailTicks(void);
u32 Motor_GetPollTailMiss(void);

/*
 * 运行时切换轮询尾帧模式，见 MOTOR_POLL_TAIL_DEFAULT 的说明。
 * 只改一个变量，定时器中断下一拍就生效，不打断正在跑的轮询。
 */
void Motor_SetPollTail(u8 mode);
u8 Motor_GetPollTail(void);

/*
 * 运行时改轮询周期（500..200000 微秒），用于验证「发太快导致电机应答队列
 * 积压」。定时器在跑时只重设 Load，不打断中断连接。
 */
int Motor_SetPollPeriod(u32 us);
u32 Motor_GetPollPeriod(void);

/*
 * 打开 / 关闭电机主动上传（手册 7.2.2 ③ 序号 9、7.5.5）。
 *
 *   enable = 1：电机每 1ms 主动发一帧实时数据，期间仍会应答主机指令
 *   enable = 0：关闭
 *
 * 发送的是扩展帧 00 05 01 00 00 00 00 00（关时第三字节为 00）。
 * 单圈模式下上传的是 6 字节标准帧：电机 ID、位置、速度、力矩。
 *
 * 两个必须注意的点：
 *   1. 1ms 一帧意味着每秒 1000 帧，RX FIFO 深 64 帧（64ms 填满）。
 *      所以接收必须走中断 + 环形缓冲（见 logger.c），主循环里不能打印
 *      每一帧，否则必然溢出、丢帧。
 *   2. 掉电不保持，电机重新上电后要补发一次。
 */
int Motor_SetAutoUpload(u8 enable);

#endif /* MOTOR_DRIVER_H */
